CREATE SCHEMA aritzia_products;
SET search_path TO aritzia_products, public;

CREATE TABLE products(
    product_no bigint PRIMARY KEY,
    product_slug text NOT NULL,
    product_full_url text NOT NULL,
    product_name text,
    product_brand text
);

CREATE TABLE colors(
    color_id text PRIMARY KEY,
    color_name text
);

CREATE TABLE product_colors(
    color_id text NOT NULL REFERENCES colors (color_id),
    product_no bigint NOT NULL REFERENCES products (product_no),
    PRIMARY KEY (color_id, product_no)
);

CREATE TABLE price_snapshots (
    color_id text NOT NULL,
    product_no bigint NOT NULL,
    original_price numeric,
    sale_price numeric,
    sale_percent numeric,
    scraped_date timestamptz NOT NULL,
    PRIMARY KEY (color_id, product_no, scraped_date),
    FOREIGN KEY (color_id, product_no)
      REFERENCES product_colors (color_id, product_no)
);

CREATE TABLE stock_snapshots (
    product_size text NOT NULL,
    color_id text NOT NULL,
    product_no bigint NOT NULL,
    product_status text,
    scraped_date timestamptz NOT NULL,
    PRIMARY KEY (product_size, color_id, product_no, scraped_date),
    FOREIGN KEY (color_id, product_no)
      REFERENCES product_colors (color_id, product_no)
);

-- Catalog snapshot read model.
CREATE TABLE catalog_snapshots (
    snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status text NOT NULL DEFAULT 'building'
      CHECK (status IN ('building', 'active', 'inactive', 'failed')),
    data_as_of timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    activated_at timestamptz
);

-- Publication replaces the active pointer transactionally; zero active rows is
-- allowed during bootstrap and building, but two active snapshots never are.
CREATE UNIQUE INDEX catalog_snapshots_one_active_idx
ON catalog_snapshots (status) WHERE status = 'active';

CREATE TABLE catalog_product_colors (
    snapshot_id bigint NOT NULL REFERENCES catalog_snapshots (snapshot_id) ON DELETE CASCADE,
    product_no bigint NOT NULL,
    color_id text NOT NULL,
    original_price numeric,
    sale_price numeric,
    effective_price numeric,
    sale_percent numeric,
    available_sizes text[] NOT NULL DEFAULT '{}',
    availability_status text NOT NULL DEFAULT 'unknown'
      CHECK (availability_status IN ('available', 'sold_out', 'unknown')),
    scraped_date timestamptz NOT NULL,
    color_name text,
    product_color_image_url text,
    swatch_image_url text,
    PRIMARY KEY (snapshot_id, product_no, color_id),
    FOREIGN KEY (color_id, product_no)
      REFERENCES product_colors (color_id, product_no)
);

CREATE INDEX catalog_product_colors_sizes_idx
ON catalog_product_colors USING gin (available_sizes);
CREATE INDEX catalog_product_colors_price_idx
ON catalog_product_colors (snapshot_id, effective_price, product_no, color_id);
CREATE INDEX catalog_product_colors_discount_idx
ON catalog_product_colors (snapshot_id, sale_percent DESC, product_no, color_id);
CREATE INDEX catalog_product_colors_observation_idx
ON catalog_product_colors (snapshot_id, scraped_date DESC, product_no, color_id);

CREATE TABLE catalog_products (
    snapshot_id bigint NOT NULL REFERENCES catalog_snapshots (snapshot_id) ON DELETE CASCADE,
    product_no bigint NOT NULL REFERENCES products (product_no),
    product_slug text,
    product_full_url text,
    product_name text,
    product_brand text,
    categories text[] NOT NULL DEFAULT '{}',
    from_color_id text,
    from_price numeric,
    from_original_price numeric,
    from_sale_percent numeric,
    availability_status text NOT NULL DEFAULT 'unknown'
      CHECK (availability_status IN ('available', 'sold_out', 'unknown')),
    tracking_started_at timestamptz,
    insight_label text,
    PRIMARY KEY (snapshot_id, product_no),
    FOREIGN KEY (snapshot_id, product_no, from_color_id)
      REFERENCES catalog_product_colors (snapshot_id, product_no, color_id)
);

CREATE INDEX catalog_products_price_idx
ON catalog_products (snapshot_id, from_price, product_no);
CREATE INDEX catalog_products_discount_idx
ON catalog_products (snapshot_id, from_sale_percent DESC, product_no);

CREATE TABLE catalog_product_price_history (
    snapshot_id bigint NOT NULL REFERENCES catalog_snapshots (snapshot_id) ON DELETE CASCADE,
    product_no bigint NOT NULL REFERENCES products (product_no),
    observation_date date NOT NULL,
    effective_price numeric,
    original_price numeric,
    sale_percent numeric,
    color_id text NOT NULL,
    PRIMARY KEY (snapshot_id, product_no, observation_date),
    FOREIGN KEY (color_id, product_no)
      REFERENCES product_colors (color_id, product_no)
);

CREATE INDEX stock_snapshots_exact_observation_idx
ON stock_snapshots (product_no, color_id, scraped_date)
INCLUDE (product_size, product_status);
